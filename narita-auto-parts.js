import {naritaScore,NARITA_PARTS} from './narita-patterns.js';
import {SIZES} from './fireworks.js?v=1.3.10';
import {tigerReservations,tigerReservationPeaks} from './adopted-tiger-programmes.js?v=1.3.30';
export {NARITA_PARTS};
export const NARITA_REVISION='narita-parts02';
const round=x=>+x.toFixed(6),overlap=(a,b)=>a.start<b.end&&b.start<a.end;
function hash(s){let h=2166136261;for(const c of s)h=Math.imul(h^c.charCodeAt(0),16777619)>>>0;return h;}
// Uses the native shell, sound, comet and adopted kotora engines. The review
// score remains immutable; only placement in the song and coordinate scale vary.
export function buildNaritaPart(id,origin,helpers,{seed=1,timeScale=1,shellFilter=null}={}){
 const score=naritaScore(id),group='narita-'+id,shots=[],fans=[];
 for(const c of score.shells){
  if(shellFilter&&!shellFilter(c))continue;
  const opening=round(origin+c.at*timeScale),ascent=helpers.shellTiming(c.kind,c.size).ascent;
  shots.push({at:round(opening-ascent),opening,anchor:opening,kind:c.kind,size:c.size,group,
   position:{naritaProgramme:true,x:c.x*.5,z:c.z*.5,launchX:c.x*.5,launchZ:c.z*.5,palette:c.palette,heightOffset:c.y*.5-SIZES[c.size].height,radiusScale:c.scale*.5,ignitionDelay:0,ascentOffset:0,reviewSeed:(seed+c.seed)>>>0}});
 }
 for(const [i,c] of score.strokes.entries()){
  if(id!=='gold-only'&&c.small&&c.at<9.2)continue;
  const at=round(origin+c.at*timeScale),style=c.white?'silver':'gold',x=c.x*.5;
  const small=c.small;
  const raw=small?{x,y:.035,z:-.30,angles:[0],count:24,height:.61,at:0,style,seed:(seed+i*977)>>>0,small:true,basicTiger:true,earlyBurn:true,spreadScale:.50,coloredTip:true}:
   {x,y:.035,z:-.30,angle:Math.atan2(c.vx,c.vy),height:c.vy*.775,at:0,style,seed:(seed+i*977)>>>0,motion:{vx:c.vx*.5,vy:c.vy*.775,burn:c.burn,drag:.11,gravity:.18*.775,afterglow:.85,tailSamples:110,headGain:1.05}};
  fans.push({at,mode:small?'small-narita-upright':'narita-strokes',style,group,options:{motionRate:1,naritaShots:[raw]}});
 }
 // Continuous lower dialogue throughout the cool three-inch opening.
 // Overlap each travelling wave with the next; use the approved open and
 // half-spread upright bundles, not the retired forced-apex trajectories.
 if(id!=='gold-only'){
  for(let wave=0;wave<14;wave++){
   const direction=wave%3,sites=Array.from({length:9},(_,i)=>i);
   if(direction===0)sites.reverse();
   if(direction===2)sites.sort((a,b)=>Math.abs(a-4)-Math.abs(b-4)||a-b);
   for(const [order,site]of sites.entries()){
    const distance=direction===2?Math.abs(site-4):order;
    const local=.20+wave*.62+distance*.085;
    if(local>9.1)continue;
    const open=(wave+site)%3!==1,style='gold';
    const raw={x:(site-4)*.46,y:.035,z:-.29,angles:[direction===2?(site-4)*.018:0],count:Math.max(8,Math.round(36*Math.min(1,timeScale))),height:open?.65:.76,at:0,style,seed:(seed+wave*977+site*137)>>>0,small:true,basicTiger:true,earlyBurn:true,spreadScale:open?1:.50,coloredTip:true};
    fans.push({at:round(origin+local*timeScale),mode:'small-narita-upright',style,group,options:{motionRate:1,naritaShots:[raw]},naritaFlow:['right-left','left-right','centre-out'][direction],naritaShape:open?'open':'compact'});
   }
  }
 }
 for(const r of score.roof)fans.push({at:round(origin+r.at*timeScale),mode:'grand-roof',style:'gold',group,options:{}});
 fans.sort((a,b)=>a.at-b.at);
 const start=Math.min(...shots.map(s=>s.at),...fans.map(f=>f.at)),end=Math.max(...shots.map(s=>s.opening+helpers.shellTiming(s.kind,s.size).life+.1),...fans.map((f,i)=>f.mode==='grand-roof'?f.at+8.5:Math.max(f.at,...tigerReservations(f,i,'narita').map(r=>r.to))));
 const budget=helpers.planBudget(shots),peaks=tigerReservationPeaks(fans.flatMap((f,i)=>tigerReservations(f,i,'narita')));
 if(budget.peakUpper>72||budget.peakPoints>600000||peaks.small>1536||peaks.large>96)throw Error('成田パーツの予約容量を超えています: '+id+' '+JSON.stringify({budget,peaks}));
 return {id,label:score.label,shots,fans,start,end,firstOpening:Math.min(...shots.map(s=>s.opening)),lastOpening:Math.max(...shots.map(s=>s.opening)),budget,groundPeaks:peaks,timeScale};
}
export function applyNaritaParts(source,analysis,options,helpers){
 if(!source.autoGenerated||source.naritaRevision)return source;
 const forced=options.naritaVariant,request=options.voiceRequest??source.voiceRequest;
 if(request?.density==='sparse'||request?.finale?.energy==='quiet')return source;
 const end=Math.min(analysis.audibleEnd??source.duration,source.finalOpening),period=analysis.period??60/(analysis.bpm||120);
 const energy=(analysis.energy??[]).filter(e=>e.time>=end-22&&e.time<end-1),level=energy.reduce((n,e)=>n+(Number(e.level)||0),0)/Math.max(1,energy.length);
 const lively=['festival','bright'].includes(source.feeling)||source.directingProfile==='rhythmic'&&level>=.55;
 const grand=source.feeling==='grand'||request?.feeling==='grand';
 if(!forced&&(!lively&&!(grand&&level>=.6)||source.feeling==='sentimental'))return source;
 const seed=hash(`${analysis.seed}|${options.variation??0}|${source.duration}|${NARITA_REVISION}`),packets=[];
 let id=forced;
 if(id&&!NARITA_PARTS.some(p=>p.id===id))throw Error('Unknown Narita part: '+id+' '+JSON.stringify({budget,peaks}));
 // Two rare tickets in twelve; both require a grand feeling and an energetic ending.
 if(!id){const ticket=seed%12;id=grand&&ticket===0?'double-two-shaku':grand&&ticket===1?'roof':seed%3===0?'gold-only':'full';}
 if(id!=='cool-rush'){
  const seconds=NARITA_PARTS.find(p=>p.id===id).seconds,origin=end-seconds;
  if(origin>=8)packets.push(buildNaritaPart(id,origin,helpers,{seed}));
 }else{
  const sec=(analysis.sections??[]).find(s=>s.end-s.at>=6&&s.at>=3&&['chorus','drop','inst','instrumental'].includes(s.role));
  const origin=(sec?.at??Math.max(4,end-12))+helpers.shellTiming('kiku',3).ascent;
  const available=Math.min(8.83,(sec?.end??end)-origin-.8),beats=[16,8,4].find(n=>n*period<=available);
  if(beats)packets.push(buildNaritaPart(id,origin,helpers,{seed,timeScale:Math.min(1,beats*period/8.83)}));
 }
 // A standalone cool-colour phrase is reserved for a sufficiently energetic,
 // separated middle section, never piled onto the ending or a quiet request.
 if(!forced&&lively&&seed%3===1){
  const finaleStart=packets[0]?.start??end-15;
  const sec=(analysis.sections??[]).find(s=>s.at>12&&s.end-s.at>=8&&s.end<finaleStart-5&&Number(s.level)>=.65&&['chorus','drop','inst','instrumental'].includes(s.role));
  if(sec){const origin=sec.at+helpers.shellTiming('kiku',3).ascent,available=sec.end-origin-.8,beats=[16,8,4].find(n=>n*period<=available);if(beats)packets.push(buildNaritaPart('cool-rush',origin,helpers,{seed:seed^0x718,timeScale:Math.min(1,beats*period/8.83)}));}
 }
 // Silence, existing field scenes and explicit ground-only windows win.
 const blockers=[...(source.fxSilenceWindows??[]),...(source.groundOnlyWindows??[]),...(source.earPassages??[]).map(w=>({start:w.start,end:w.end}))].filter(w=>Number.isFinite(w.start)&&Number.isFinite(w.end));
 const accepted=packets.filter(p=>p.start>=.1&&!blockers.some(w=>overlap(p,w)));
 if(!accepted.length)return source;
 const shotWindow=s=>({start:s.at,end:s.opening+helpers.shellTiming(s.kind,s.size).life+.1});
 const groupIsOurs=g=>String(g).startsWith('narita-');
 const shots=[...source.shots.filter(s=>!accepted.some(p=>overlap(p,shotWindow(s)))),...accepted.flatMap(p=>p.shots)].sort((a,b)=>a.at-b.at);
 const fans=[...source.fans.filter(f=>!accepted.some(p=>overlap(p,{start:f.at,end:f.at+9}))),...accepted.flatMap(p=>p.fans)].sort((a,b)=>a.at-b.at);
 shots.forEach((s,i)=>{if(groupIsOurs(s.group))s.reviewIndex=i;});
 const finale=accepted.find(p=>p.id!=='cool-rush'),summary=accepted.map(({shots,fans,...p})=>({...p,shellCount:shots.length,groundCueCount:fans.length}));
 return {...source,shots,fans,naritaRevision:NARITA_REVISION,naritaPassages:summary,
  ...(finale?{finale:{kind:'narita-'+finale.id,label:finale.label},finalPreviewStart:Math.max(0,finale.start-1)}:{}),
  sections:[...source.sections.filter(s=>!accepted.some(p=>s.at>=p.start&&s.at<=p.lastOpening)),...accepted.map(p=>({at:p.start,label:p.label}))].sort((a,b)=>a.at-b.at),
  showDuration:Math.max(source.showDuration,...accepted.map(p=>p.end+1)),budget:helpers.planBudget(shots),
  analysisSummary:{...source.analysisSummary,naritaParts:summary.map(p=>p.id),fastSmallShots:shots.filter(s=>s.group==='narita-cool-rush'||s.size===3&&s.group==='narita-full').length,goldSmallShots:shots.filter(s=>s.size===3&&['silver','willow'].includes(s.kind)).length,shellKinds:[...new Set(shots.map(s=>s.kind))],groundModes:[...new Set(fans.map(f=>f.mode))]},
  method:source.method+'; Quest-reviewed Narita modular scores; explicit per-passage reservation, stable rare draw, continuous upper and lower dialogue.'};
}
