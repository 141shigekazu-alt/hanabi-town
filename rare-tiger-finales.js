// An eligible grand ending may draw a rare effect; pop tracks never enter.
// Stable plan/variation seeds preserve favourites and repeat playback.
export const RARE_TIGER_DRAW_MODULUS=6;
function hash(text){let n=2166136261;for(const c of text)n=Math.imul(n^c.charCodeAt(0),16777619)>>>0;return n;}
export function rareTigerFinaleProposal(plan,trackId=''){
 const grand=plan.feeling==='grand'||plan.voiceRequest?.feeling==='grand';
 if(!plan.autoGenerated||!grand||plan.voiceRequest?.density==='sparse')return null;
 const end=plan.finalOpening;if(!Number.isFinite(end)||end<14)return null;
 const kamuro=(plan.shots??[]).filter(s=>['silver','willow'].includes(s.kind)&&s.size>=5&&s.opening>=end-6&&s.opening<=end+1.5);
 if(!kamuro.some(s=>s.size>=10))return null;
 const seed=hash([trackId,plan.analysisSummary?.variation??0,plan.duration,plan.finale?.kind??'',plan.revision].join('|'));
 if(seed%RARE_TIGER_DRAW_MODULUS!==0)return null;
 const sync=kamuro.length>=5&&((seed>>>7)&1)===1,start=end-(sync?8.4:5.3),stop=end+2;
 if((plan.fxSilenceWindows??[]).some(w=>w.start<stop&&w.end>start))return null;
 const group='rare-grand-tiger-finale',added=sync?[
  {at:start,mode:'sync-fan',style:'gold',group,options:{smallStyle:'grand-yellow'}},
  {at:end-3.8,mode:'sync-fan',style:'gold',group,options:{smallStyle:'grand-yellow'}},
  {at:end+.3,mode:'small-wide-fan',style:'grand-yellow',group,options:{ignition:'together'}}
 ]:[{at:start,mode:'grand-roof',style:'gold',group,options:{}}];
 const fans=[...plan.fans.filter(f=>f.at<start||f.at>=stop),...added].sort((a,b)=>a.at-b.at);
 return {fans,kind:sync?'grand-sync-finale':'grand-roof',seed,drawModulus:RARE_TIGER_DRAW_MODULUS,showDuration:Math.max(plan.showDuration??plan.duration,start+(sync?12:8.5)),added};
}
